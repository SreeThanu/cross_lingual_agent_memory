# --- D6 case 7-11: eligibility, validity, reconciliation, determinism ------------------


def test_failed_write_is_excluded_and_counted_write_ineligible() -> None:
    """f_1 not written, f_2 written and stale -> eligible 1, SR 1/1, write-ineligible 1/2."""
    rep = compute_staleness_v2(
        [ALLERGY, CITY],
        ["f_1", "f_2"],
        {"f_2"},
        [_reprobe("f_1", "You are allergic to cashews."), _reprobe("f_2", "You live in Pune.")],
        None,
    )
    assert rep["write_ineligible_count"] == 1
    assert rep["eligible_corrections"] == 1
    assert rep["staleness_rate"] == pytest.approx(1.0)
    assert rep["write_ineligible_rate"] == pytest.approx(0.5)


def test_all_corrections_write_ineligible_gives_null_sr() -> None:
    rep = compute_staleness_v2([ALLERGY], ["f_1"], set(), [_reprobe("f_1", "cashews")], None)
    assert rep["staleness_rate"] is None and rep["miss_rate"] is None
    assert rep["write_ineligible_rate"] == pytest.approx(1.0)
    assert "no eligible corrections" in rep["invalid_reason"]


@pytest.mark.parametrize("n_records", [0, 2])
def test_missing_or_duplicate_reprobe_is_invalid_never_success(n_records: int) -> None:
    """A written correction with 0 or 2 re-probe records -> SR null for the seed, not 0.0."""
    rows = [_reprobe("f_1", "You are allergic to cashews.")] * n_records
    rep = compute_staleness_v2([ALLERGY], ["f_1"], {"f_1"}, rows, None)
    assert rep["missing_or_invalid_reprobe_count"] == 1
    assert rep["staleness_rate"] is None
    assert "without a valid re-probe" in rep["invalid_reason"]


def test_no_correction_turn_gives_null_sr() -> None:
    """A fact with update data but no correction turn is not in the denominator -> null."""
    rep = compute_staleness_v2([ALLERGY], [], {"f_1"}, [], None)
    assert rep["staleness_rate"] is None
    assert rep["invalid_reason"] == "no correction turn in run_log.jsonl"
    assert rep["corrected_count"] == 0


def test_counts_reconcile_with_denominators() -> None:
    """4 corrected: f_1 UPDATED, f_2 STALE, f_3 MISS, f_4 write-ineligible.

    eligible = 3 -> SR = 1/3, MR = 1/3; write-ineligible rate = 1/4.
    """
    rep = compute_staleness_v2(
        [ALLERGY, CITY, EMPLOYER, PET],
        ["f_1", "f_2", "f_3", "f_4"],
        {"f_1", "f_2", "f_3"},
        [
            _reprobe("f_1", "You are allergic to cashews."),
            _reprobe("f_2", "You live in Pune."),
            _reprobe("f_3", "You work at Wipro."),
            _reprobe("f_4", "A beagle."),
        ],
        None,
    )
    assert (rep["updated_count"], rep["stale_count"], rep["miss_count"]) == (1, 1, 1)
    assert rep["eligible_corrections"] == 3
    assert rep["corrected_count"] == (
        rep["eligible_corrections"]
        + rep["write_ineligible_count"]
        + rep["missing_or_invalid_reprobe_count"]
    )
    assert rep["staleness_rate"] == pytest.approx(1 / 3)
    assert rep["miss_rate"] == pytest.approx(1 / 3)
    assert rep["write_ineligible_rate"] == pytest.approx(0.25)
    assert [p["status"] for p in rep["per_fact"]] == [UPDATED, STALE, MISS, "write_ineligible"]


