def test_write_fidelity_hand_computed(
    hand_computed_facts: list[Fact],
    hand_computed_memories: list[Memory],
) -> None:
    """Hand-computed: 4 out of 5 facts stored -> WF = 4/5 = 0.80.

    f_4 ('marathi') was not stored.
    """
    wf, written_ids = compute_write_fidelity(hand_computed_facts, hand_computed_memories)
    assert wf == pytest.approx(0.80, abs=1e-4)
    assert set(written_ids) == {"f_1", "f_2", "f_3", "f_5"}
    assert "f_4" not in written_ids


