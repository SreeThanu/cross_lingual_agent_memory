def test_false_merge_rate_hand_computed(
    hand_computed_distractor_pairs: list[tuple[Fact, Fact]],
    hand_computed_memories: list[Memory],
) -> None:
    """Hand-computed FMR: No collapsed memory records -> FMR = 0/1 = 0.00."""
    fmr = compute_false_merge_rate(hand_computed_distractor_pairs, hand_computed_memories)
    assert fmr == pytest.approx(0.00, abs=1e-4)

    # Now create a collapsed memory
    collapsed_store = [
        Memory(raw_id="mc", text="User and user's sister are both allergic to peanuts."),
    ]
    # For a value-shift pair where both values merge:
    f_base = Fact(id="b", domain="h", entity="u", relation="r", value="apple", surface={"en": "apple"})
    f_dist = Fact(id="d", domain="h", entity="u", relation="r", value="orange", surface={"en": "orange"}, distractor_of="b")
    merged_store = [Memory(raw_id="m_merged", text="User likes apple and orange.")]
    fmr_merged = compute_false_merge_rate([(f_base, f_dist)], merged_store)
    assert fmr_merged == pytest.approx(1.00, abs=1e-4)


def test_recall_at_k_and_write_first_ordering(
    hand_computed_facts: list[Fact],
    hand_computed_memories: list[Memory],
) -> None:
    """Hand-computed Recall:

    Probe results on written facts {f_1, f_2, f_3, f_5}:
      f_1 -> retrieves m1 ('peanut') -> HIT
      f_2 -> retrieves unrelated -> MISS
      f_3 -> retrieves m3 ('Infosys') -> HIT
      f_5 -> retrieves m5 ('golden retriever') -> HIT
    Strict hits = 3/4 = 0.75 on written facts.

    CRITICAL INVARIANT CHECK:
    If f_4 (missing from dump) were wrongly counted as a retrieval failure,
    recall would be 3/5 = 0.60. Write-first filtering ensures 3/4 = 0.75.
    """
    probe_results = [
        ProbeResult(fact_id="f_1", store_lang="hi", probe_lang="en", retrieved=[hand_computed_memories[0]], response="peanuts", hit_strict=True),
        ProbeResult(fact_id="f_2", store_lang="hi", probe_lang="en", retrieved=[Memory(raw_id="x", text="unrelated")], response="I don't know", hit_strict=False),
        ProbeResult(fact_id="f_3", store_lang="hi", probe_lang="en", retrieved=[hand_computed_memories[2]], response="Infosys", hit_strict=True),
        ProbeResult(fact_id="f_4", store_lang="hi", probe_lang="en", retrieved=[], response="No idea", hit_strict=False),
        ProbeResult(fact_id="f_5", store_lang="hi", probe_lang="en", retrieved=[hand_computed_memories[4]], response="golden retriever", hit_strict=True),
    ]

    _, written_ids = compute_write_fidelity(hand_computed_facts, hand_computed_memories)

    # Evaluated on written facts: 3 hits out of 4 written
    recall_written = compute_recall_at_k(hand_computed_facts, probe_results, k=1, mode="strict", eligible_fact_ids=set(written_ids))
    assert recall_written == pytest.approx(0.75, abs=1e-4)

    # Raw unpartitioned recall on all 5 facts would be 3/5 = 0.60
    recall_raw = compute_recall_at_k(hand_computed_facts, probe_results, k=1, mode="strict", eligible_fact_ids=None)
    assert recall_raw == pytest.approx(0.60, abs=1e-4)


def test_ltg_hand_computed() -> None:
    """Hand-computed LTG:

    Same-lang recalls: [0.90, 0.86] -> mean = 0.88
    Cross-lang recalls: [0.65, 0.71] -> mean = 0.68
    LTG = 0.88 - 0.68 = 0.20
    """
    ltg = compute_ltg(same_lang_recalls=[0.90, 0.86], cross_lang_recalls=[0.65, 0.71])
    assert ltg == pytest.approx(0.20, abs=1e-4)


def test_encoding_asymmetry_hand_computed() -> None:
    """Hand-computed EA:

    recall(store=hi) = 0.60
    recall(store=en) = 0.75
    EA = 0.60 - 0.75 = -0.15 (English storage is superior by 15 percentage points)
    """
    ea = compute_encoding_asymmetry(recall_stored_hi=0.60, recall_stored_en=0.75)
    assert ea == pytest.approx(-0.15, abs=1e-4)


def test_staleness_rate_hand_computed(hand_computed_facts: list[Fact]) -> None:
    """Hand-computed SR:

    f_2 updated from 'pune' to 'mumbai'.
    Re-probe returns: 'You live in Pune and Mumbai.' -> contains stale value 'pune'!
    SR = 1/1 = 1.00 (100%).
    """
    f2 = hand_computed_facts[1]
    reprobe_stale = [
        ProbeResult(
            fact_id="f_2",
            store_lang="hi",
            probe_lang="en",
            retrieved=[Memory(raw_id="m_u", text="User lives in Mumbai and Pune")],
            response="You live in Pune and Mumbai.",
            hit_strict=False,
        )
    ]
    sr = compute_staleness_rate(corrected_facts=[f2], reprobe_results=reprobe_stale)
    assert sr == pytest.approx(1.00, abs=1e-4)

    # When stale value is completely cleared:
    reprobe_clean = [
        ProbeResult(
            fact_id="f_2",
            store_lang="hi",
            probe_lang="en",
            retrieved=[Memory(raw_id="m_u", text="User lives in Mumbai")],
            response="You live in Mumbai.",
            hit_strict=True,
        )
    ]
    sr_clean = compute_staleness_rate(corrected_facts=[f2], reprobe_results=reprobe_clean)
    assert sr_clean == pytest.approx(0.00, abs=1e-4)
